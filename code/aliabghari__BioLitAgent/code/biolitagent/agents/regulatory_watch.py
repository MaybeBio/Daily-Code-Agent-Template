async def _watch_source(
    source: dict[str, Any],
    state: dict[str, Any],
    playwright_page: Optional[Page],
    dry_run: bool,
) -> ExtractionStatus:
    """
    Process one regulatory source: fetch, compare, extract, emit.

    Returns an ExtractionStatus so the caller (run()) can accumulate a
    per-source summary without any failure mode being silently swallowed.

    *playwright_page* must be a live Playwright Page if source['requires_js']
    is true; it may be None for static pages.
    """
    source_id = source["id"]
    agency = source.get("agency", "Unknown")
    index_url = source["url"]
    requires_js = source.get("requires_js", False)
    wait_selector = source.get("wait_selector")

    log.info("-- %-5s | %s", agency, index_url)

    # -- Fetch ----------------------------------------------------------------
    try:
        if requires_js:
            if playwright_page is None:
                raise RuntimeError(
                    f"Source '{source_id}' requires JS rendering but no "
                    "Playwright page was provided."
                )
            html = await _fetch_js_rendered(playwright_page, index_url, wait_selector)
        else:
            html = await _fetch_static(index_url)
    except Exception as exc:
        log.error("  -> [FETCH_ERROR] %s: %s", index_url, exc)
        return ExtractionStatus.FETCH_ERROR

    # -- Normalise and hash ---------------------------------------------------
    current_text = _extract_visible_text(html)
    current_hash = sha256_of(current_text)

    previous_entry = state.get(source_id, {})
    previous_hash: Optional[str] = previous_entry.get("hash")
    previous_text: Optional[str] = previous_entry.get("text_snippet")

    if _daily_quota_exhausted:
        log.warning("  -> [SKIPPED_QUOTA_EXHAUSTED] %s -- Daily Gemini quota exhausted; skipping without calling API.", index_url)
        return ExtractionStatus.SKIPPED_QUOTA_EXHAUSTED

    if current_hash == previous_hash:
        log.info("  -> [NO_CHANGE] Hash match (%s...) -- skipping LLM call.", current_hash[:12])
        return ExtractionStatus.NO_CHANGE

    log.info(
        "  -> Change detected (prev=%s... -> curr=%s...) -- running LLM extraction.",
        (previous_hash or "none")[:12],
        current_hash[:12],
    )

    # -- LLM extraction -------------------------------------------------------
    cached_result: Optional[ExtractionResult] = None
    is_cache_hit: bool = False
    if dry_run:
        cached_result = get_cached_llm_response(current_hash)

    if cached_result is not None:
        log.info("[DRY RUN] Cache hit for %s -- skipping LLM call", current_hash)
        log.info("[CACHE_HIT] Using cached extraction for %s, skipping Gemini call", source_id)
        result = cached_result
        is_cache_hit = True
    else:
        global _preflight_checked
        if not _preflight_checked:
            if not check_preflight_gate(1, "regulatory_watch"):
                log.info("[QUOTA_GUARD] Pre-flight gate aborted by reviewer -- skipping extraction.")
                return ExtractionStatus.SKIPPED_QUOTA_EXHAUSTED
            _preflight_checked = True

        result = await _extract_items_via_llm(
            agency=agency,
            index_url=index_url,
            current_text=current_text,
            previous_text=previous_text,
        )
        # Only write to this cache after a successful real API call (dry-run only)
        if dry_run and result.status in (ExtractionStatus.ITEMS_FOUND, ExtractionStatus.NO_NEW_ITEMS):
            cache_llm_response(
                content_hash=current_hash,
                source_id=source_id,
                result=result,
            )

    if result.status == ExtractionStatus.SKIPPED_QUOTA_EXHAUSTED:
        return ExtractionStatus.SKIPPED_QUOTA_EXHAUSTED

    # Emit pending records only on success.
    if result.status == ExtractionStatus.ITEMS_FOUND:
        for item in result.items:
            record = _build_record(source, item, content_hash=current_hash)
            _append_record(record, dry_run=dry_run)

    # -- Update state entry ---------------------------------------------------
    # Update state for any outcome where we actually fetched and hashed the page,
    # even if LLM extraction failed -- so that a transient API error doesn't cause
    # the same changed page to be re-submitted on every subsequent run.
    # Exception: do NOT update state on FETCH_ERROR (handled above by early return),
    # NO_CHANGE (state already current), or SKIPPED_QUOTA_EXHAUSTED (retry next day).
    state[source_id] = {
        "hash": current_hash,
        "last_checked": datetime.now(timezone.utc).isoformat(),
        # Small snippet for LLM diff context on the next run.
        "text_snippet": current_text[:_STATE_SNIPPET_CHARS],
        # Persist the last extraction status for debugging.
        "last_extraction_status": result.status.value,
    }

    return ExtractionStatus.CACHE_HIT if is_cache_hit else result.status



