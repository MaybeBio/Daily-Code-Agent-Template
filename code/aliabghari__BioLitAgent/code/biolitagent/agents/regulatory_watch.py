#!/usr/bin/env python3
"""
agents/regulatory_watch.py
--------------------------
Regulatory Watch Agent for BioLitAgent.

Visits the configured FDA, EMA, and ICH guidance index pages, detects new or
changed guidance documents since the last recorded check, and appends
structured records to storage/pending_items.jsonl.

How change detection works
--------------------------
1. Each source page is fetched (via Playwright for JS SPAs, httpx otherwise).
2. The visible text is normalised and SHA-256 hashed.
3. If the hash differs from the stored hash for that source, the page is flagged
   as changed.  The Gemini API is then asked to identify which items are new or
   updated and to write a 2-3 sentence paraphrase of each (no verbatim copying).
4. Resulting records are appended to storage/pending_items.jsonl.
5. The state file (storage/regulatory_state.json) is updated with the new hash
   and a lightweight text snippet used as context on the next run.

Usage
-----
    python agents/regulatory_watch.py [--dry-run] [--headed] [--model MODEL]
    python agents/regulatory_watch.py --sources path/to/other_sources.json

CLI flags
---------
    --dry-run       Detect changes but do not write output or update state.
    --headed        Open a visible browser window (useful for debugging JS SPAs).
    --model MODEL   Gemini model name for extraction (default: gemini-3.8-flash).
    --sources PATH  Override the default regulatory_sources.json path.

Environment variables (from .env -- see .env.example)
-----------------------------------------------------
    GOOGLE_API_KEY  Required for LLM-based extraction and paraphrase generation.

Dependencies
------------
    pip install playwright httpx beautifulsoup4 google-genai python-dotenv
    playwright install chromium

Output schema  (one JSON object per line in pending_items.jsonl)
----------------------------------------------------------------
    {
      "id":               "<uuidv4>",
      "source_type":      "regulatory",
      "title":            "<guidance document title>",
      "agency":           "FDA | EMA | ICH",
      "url":              "<direct link to document, or null>",
      "url_unknown":      "<true if no direct URL was found on the page>",
      "publication_date": "<YYYY-MM-DD, or null>",
      "date_unknown":     "<true if no publication date was found on the page>",
      "description":      "<2-3 sentence paraphrase -- NOT verbatim regulatory text>",
      "detected_at":      "<ISO 8601 UTC timestamp>",
      "content_hash":     "<sha256 hex of the page text at detection time>",
      "source_id":        "<id from regulatory_sources.json>",
      "index_url":        "<URL of the index page that was monitored>"
    }

IMPORTANT -- copyright / compliance note
----------------------------------------
The description field must always be an original paraphrase generated by the
LLM.  Verbatim reproduction of FDA, EMA, or ICH regulatory text is explicitly
prohibited by this agent's design.  The LLM prompt enforces this constraint.
"""

