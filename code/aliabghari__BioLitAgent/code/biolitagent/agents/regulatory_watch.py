async def _fetch_static(url: str, timeout_s: int = 30) -> str:
    """Fetch a non-JS page with httpx and return the raw HTML."""
    if not _HTTPX_AVAILABLE:
        raise RuntimeError("httpx is not installed.  pip install httpx")
    async with httpx.AsyncClient(
        headers={"User-Agent": _UA},
        follow_redirects=True,
        timeout=timeout_s,
    ) as client:
        response = await client.get(url)
        response.raise_for_status()
        return response.text


async def _fetch_js_rendered(
    page: Page,
    url: str,
    wait_selector: Optional[str],
    timeout_ms: int = 45_000,
) -> str:
    """Navigate Playwright to *url*, wait for content to stabilise, return HTML."""
    try:
        await page.goto(url, wait_until="networkidle", timeout=timeout_ms)
    except PWTimeoutError:
        log.warning("networkidle timed out for %s -- falling back to domcontentloaded", url)
        await page.goto(url, wait_until="domcontentloaded", timeout=timeout_ms)

    if wait_selector:
        try:
            await page.wait_for_selector(wait_selector, timeout=timeout_ms)
        except PWTimeoutError:
            log.warning("Selector '%s' not found on %s -- proceeding anyway.", wait_selector, url)

    return await page.content()


def _extract_visible_text(html: str) -> str:
    """
    Strip navigation chrome and return clean, deduplicated visible text.
    Falls back to simple regex stripping if BeautifulSoup is unavailable.
    """
    if _BS4_AVAILABLE:
        soup = BeautifulSoup(html, "html.parser")
        for tag in soup(["script", "style", "nav", "footer", "header", "noscript"]):
            tag.decompose()
        raw = soup.get_text(separator="\n")
    else:
        # Minimal fallback: strip HTML tags
        raw = re.sub(r"<[^>]+>", " ", html)

    lines = [ln.strip() for ln in raw.splitlines()]
    return "\n".join(ln for ln in lines if ln)


