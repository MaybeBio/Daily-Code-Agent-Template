def load_state() -> dict[str, Any]:
    """Load the persisted per-source hash state from disk."""
    if _STATE_FILE.exists():
        try:
            return json.loads(_STATE_FILE.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            log.warning(
                "regulatory_state.json is corrupt -- starting from a clean state. "
                "All enabled sources will be treated as first-visit."
            )
    return {}


def save_state(state: dict[str, Any]) -> None:
    """Persist the updated per-source hash state to disk."""
    _STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    _STATE_FILE.write_text(
        json.dumps(state, indent=2, ensure_ascii=False, sort_keys=True),
        encoding="utf-8",
    )
    log.debug("State saved -> %s", _STATE_FILE)


