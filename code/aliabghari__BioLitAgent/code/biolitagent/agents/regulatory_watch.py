_EXTRACT_PROMPT = """\
You are an expert regulatory affairs scientist helping to monitor {agency} guidance publications.

The text below is the CURRENT content of the guidance index page at:
  {url}

{diff_context}

YOUR TASK
---------
1. Identify guidance documents that appear to be NEW or RECENTLY UPDATED on this page
   compared to the previous snapshot (if one exists).
2. For each such document, return ALL of the following fields:

     title            - the exact title of the guidance document.

     publication_date - the publication or revision date in YYYY-MM-DD format.
                        If the date is visible but only partially (e.g. "June 2024"),
                        convert it to the best available precision (e.g. "2024-06-01").
                        If NO date is visible anywhere on the page for this item, set
                        this field to null AND set "date_unknown": true.

     url              - the full absolute URL (https://...) linking directly to the
                        guidance document PDF or detail page, as found in the page text.
                        If NO direct link is visible for this item, set this field to
                        null AND set "url_unknown": true.

     description      - 2 to 3 sentences, IN YOUR OWN WORDS, describing what this
                        guidance covers and why it is noteworthy.
                        DO NOT copy verbatim text from the page.
                        DO NOT quote regulatory document language directly.

     date_unknown     - (boolean) true if and only if publication_date could not be
                        determined from the page. Omit or set false if a date was found.

     url_unknown      - (boolean) true if and only if no direct document URL could be
                        found on the page. Omit or set false if a URL was found.

3. If no new or changed items are identifiable, return an empty JSON array.

OUTPUT FORMAT
-------------
Return ONLY a valid JSON array -- no markdown fences, no prose before or after:
[
  {{
    "title": "...",
    "publication_date": "YYYY-MM-DD or null",
    "date_unknown": false,
    "url": "https://... or null",
    "url_unknown": false,
    "description": "..."
  }}
]

PAGE TEXT (up to {max_chars} characters):
{page_text}
"""

# Transient HTTP status codes that warrant a retry against the Gemini API.
_RETRYABLE_STATUS_CODES = {429, 503}
# Maximum number of retry attempts for transient API errors.
_MAX_LLM_RETRIES = 3
# Base backoff in seconds; actual delay = _BACKOFF_BASE * 2^attempt (2s, 4s, 8s).
_BACKOFF_BASE = 2.0


async def _extract_items_via_llm(
    agency: str,
    index_url: str,
    current_text: str,
    previous_text: Optional[str],
) -> ExtractionResult:
    """
    Ask Gemini to identify new / changed guidance items and return an ExtractionResult.

    Structured JSON output
    ----------------------
    The API call uses response_mime_type="application/json" (and response_schema
    when available) so the model is constrained to emit valid JSON without any
    wrapping prose.  Fence-stripping is applied as a defense-in-depth fallback
    in case the model or an intermediate proxy re-wraps the output.

    Retry behaviour
    ---------------
    Retries up to _MAX_LLM_RETRIES times on transient 503 / 429 errors with
    exponential backoff (2 s, 4 s, 8 s).

    Return values
    -------------
    ExtractionResult.status is always one of:
      SKIPPED_API_ERROR   - Gemini API failed after all retries.
      SKIPPED_PARSE_ERROR - API responded; output was not valid JSON / wrong shape.
      NO_NEW_ITEMS        - Parsed successfully; model found no new items.
      ITEMS_FOUND         - Parsed successfully; one or more items returned.
    """
    client = _get_llm_client()

    if previous_text:
        diff_context = (
            "A PREVIOUS SNAPSHOT of this page exists. "
            "Focus exclusively on items that are NEW or REVISED since the last run. "
            "Ignore items that appeared in the previous snapshot unchanged."
        )
    else:
        diff_context = (
            "NO PREVIOUS SNAPSHOT exists -- this is the first visit to this source. "
            "Return up to the 5 most recently published or updated items visible on the page."
        )

    prompt = _EXTRACT_PROMPT.format(
        agency=agency,
        url=index_url,
        diff_context=diff_context,
        max_chars=_MAX_LLM_CHARS,
        page_text=current_text[:_MAX_LLM_CHARS],
    )

    # -- Build the GenerateContentConfig with structured JSON output -----------
    # response_mime_type constrains the model to emit a bare JSON document.
    # response_schema (a JSON Schema object) further constrains the shape.
    # Both are supported by Gemini 1.5+ / 2.0+; we guard against SDK versions
    # that don't yet expose response_schema via hasattr inspection.
    _item_schema = {
        "type": "array",
        "items": {
            "type": "object",
            "properties": {
                "title":            {"type": "string"},
                "publication_date": {"type": ["string", "null"]},
                "date_unknown":     {"type": "boolean"},
                "url":              {"type": ["string", "null"]},
                "url_unknown":      {"type": "boolean"},
                "description":      {"type": "string"},
            },
            "required": ["title", "description"],
        },
    }

    config_kwargs: dict[str, Any] = {
        "temperature": 0.1,
        "max_output_tokens": 8192,
        "response_mime_type": "application/json",
    }
    # response_schema was added in google-genai >= 0.7; skip gracefully if absent.
    if hasattr(genai_types.GenerateContentConfig, "response_schema"):
        config_kwargs["response_schema"] = _item_schema

    gen_config = genai_types.GenerateContentConfig(**config_kwargs)

    # -- API call with retry-backoff -------------------------------------------
    global _daily_quota_exhausted
    if _daily_quota_exhausted:
        return ExtractionResult(
            status=ExtractionStatus.SKIPPED_QUOTA_EXHAUSTED,
            detail="Daily Gemini quota exhausted.",
        )

    last_exc: Optional[Exception] = None
    response = None

    for attempt in range(_MAX_LLM_RETRIES + 1):
        try:
            record_call("regulatory_watch")
            response = client.models.generate_content(
                model=_llm_model,
                contents=prompt,
                config=gen_config,
            )
            break  # success -- exit retry loop

        except Exception as exc:  # noqa: BLE001
            last_exc = exc
            exc_str = str(exc)

            is_quota, quota_id, retry_delay = parse_quota_failure(exc)
            if is_quota and is_daily_exhaustion(quota_id, exc_str):
                _daily_quota_exhausted = True
                msg = (
                    f"Daily Gemini quota exhausted (quotaId: {quota_id or 'PerDay'}): {exc}"
                )
                log.warning("  -> [SKIPPED_QUOTA_EXHAUSTED] %s -- %s", index_url, msg)
                return ExtractionResult(
                    status=ExtractionStatus.SKIPPED_QUOTA_EXHAUSTED,
                    detail=msg,
                )

            # Detect retryable status codes embedded in the exception message.
            is_retryable = any(
                f"{code}" in exc_str
                or f"HTTP {code}" in exc_str
                or f"status {code}" in exc_str
                for code in _RETRYABLE_STATUS_CODES
            )

            if is_retryable and attempt < _MAX_LLM_RETRIES:
                delay = _BACKOFF_BASE * (2 ** attempt)  # 2s, 4s, 8s
                log.warning(
                    "  -> [RETRY %d/%d] Transient Gemini API error for %s "
                    "(retrying in %.0fs): %s",
                    attempt + 1,
                    _MAX_LLM_RETRIES,
                    index_url,
                    delay,
                    exc,
                )
                await asyncio.sleep(delay)
            else:
                # Non-retryable, or this was the last allowed attempt.
                msg = (
                    f"Gemini API failed after {attempt + 1}/{_MAX_LLM_RETRIES} "
                    f"attempt(s): {exc}"
                )
                log.error("  -> [SKIPPED_API_ERROR] %s -- %s", index_url, msg)
                return ExtractionResult(
                    status=ExtractionStatus.SKIPPED_API_ERROR,
                    detail=msg,
                )

    if response is None:
        # for-else: loop ran to completion without a successful break.
        msg = (
            f"Gemini API failed after {_MAX_LLM_RETRIES}/{_MAX_LLM_RETRIES} "
            f"attempt(s): {last_exc}"
        )
        log.error("  -> [SKIPPED_API_ERROR] %s -- %s", index_url, msg)
        return ExtractionResult(
            status=ExtractionStatus.SKIPPED_API_ERROR,
            detail=msg,
        )

    # -- Parse the response ----------------------------------------------------
    raw = (response.text or "").strip()

    # Defense-in-depth: strip markdown fences in case a proxy re-wraps output.
    # Pattern covers ```json\n...\n``` and ``` \n...\n ```.
    fence_match = re.match(r"^```(?:json)?\s*\n?(.*?)\n?```\s*$", raw, re.DOTALL)
    if fence_match:
        raw = fence_match.group(1).strip()

    # An empty string or bare "[]" from the model means no items found.
    if not raw or raw == "[]":
        log.info("  -> [NO_NEW_ITEMS] %s -- model returned an empty result.", index_url)
        return ExtractionResult(
            status=ExtractionStatus.NO_NEW_ITEMS,
            detail="Model returned empty JSON array.",
        )

    try:
        parsed = json.loads(raw)
        if not isinstance(parsed, list):
            raise ValueError(f"Expected JSON array, got {type(parsed).__name__}")
    except (json.JSONDecodeError, ValueError) as exc:
        msg = f"{type(exc).__name__}: {exc}"
        log.error(
            "  -> [SKIPPED_PARSE_ERROR] %s -- could not parse LLM output as JSON.\n"
            "    Error: %s\n"
            "    Raw output (first 500 chars): %.500s",
            index_url,
            msg,
            raw,
        )
        return ExtractionResult(
            status=ExtractionStatus.SKIPPED_PARSE_ERROR,
            detail=msg,
        )

    if not parsed:
        log.info("  -> [NO_NEW_ITEMS] %s -- model found no new or changed items.", index_url)
        return ExtractionResult(
            status=ExtractionStatus.NO_NEW_ITEMS,
            detail="Parsed successfully; zero items returned.",
        )

    log.info("  -> [ITEMS_FOUND] %s -- %d item(s) extracted.", index_url, len(parsed))
    return ExtractionResult(
        status=ExtractionStatus.ITEMS_FOUND,
        items=parsed,
        detail=f"{len(parsed)} item(s) extracted.",
    )


