def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="regulatory_watch",
        description=(
            "BioLitAgent Regulatory Watch Agent -- detects new/changed FDA, EMA, "
            "and ICH guidance documents and appends structured records to "
            "storage/pending_items.jsonl."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--sources",
        metavar="PATH",
        default=str(_DEFAULT_SOURCES),
        help="Path to regulatory_sources.json.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Detect changes but do not write output files or update state.",
    )
    parser.add_argument(
        "--headed",
        action="store_true",
        help="Launch a visible browser window (useful for debugging JS SPAs).",
    )
    parser.add_argument(
        "--model",
        metavar="MODEL",
        default=_DEFAULT_MODEL,
        help="Gemini model for extraction and paraphrase generation.",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable DEBUG-level log output.",
    )
    return parser


def main() -> None:
    parser = _build_parser()
    args = parser.parse_args()

    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    # Push model choice into module-level variable used by _get_llm_client.
    global _llm_model
    _llm_model = args.model

    exit_code = asyncio.run(run(args))
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
