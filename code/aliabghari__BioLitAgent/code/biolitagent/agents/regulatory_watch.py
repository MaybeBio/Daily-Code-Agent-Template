# Status display metadata: (label, log-level method name, short description)
_STATUS_META: dict[ExtractionStatus, tuple[str, str, str]] = {
    ExtractionStatus.ITEMS_FOUND:             ("[OK] ITEMS_FOUND",             "info",    "new items extracted and written"),
    ExtractionStatus.CACHE_HIT:               ("[CACHE_HIT] CACHE_HIT",         "info",    "used cached LLM extraction; LLM call skipped"),
    ExtractionStatus.NO_NEW_ITEMS:            ("[OK]  NO_NEW_ITEMS",            "info",    "checked; no new items found"),
    ExtractionStatus.NO_CHANGE:               ("-  NO_CHANGE",               "info",    "page hash unchanged; LLM skipped"),
    ExtractionStatus.SKIPPED_QUOTA_EXHAUSTED: ("[!]  SKIPPED_QUOTA_EXHAUSTED", "warning", "daily Gemini quota exhausted; skipped without calls"),
    ExtractionStatus.SKIPPED_PARSE_ERROR:     ("[!]  SKIPPED_PARSE_ERROR",     "warning", "API responded but output was unparseable"),
    ExtractionStatus.FETCH_ERROR:             ("[X]  FETCH_ERROR",             "error",   "page could not be fetched"),
    ExtractionStatus.SKIPPED_API_ERROR:       ("[X]  SKIPPED_API_ERROR",       "error",   "Gemini API failed after all retries"),
}


def _print_run_summary(summary: dict[str, ExtractionStatus]) -> None:
    """
    Print a per-source status table and a count breakdown at end-of-run.

    Each source gets exactly one line so that:
      * A source that was checked and found clean is clearly labelled NO_NEW_ITEMS
        or NO_CHANGE, not collapsed into the same output as an errored source.
      * SKIPPED_API_ERROR, SKIPPED_PARSE_ERROR, and FETCH_ERROR are visually
        distinct and always appear explicitly in the log.
    """
    if not summary:
        log.info("Run summary: no sources were processed.")
        return

    col_w = max(len(sid) for sid in summary) + 2
    sep = "-" * (col_w + 30)

    log.info("")
    log.info("+%s+", sep)
    log.info("|  RUN SUMMARY -- %d source(s) processed%s|",
             len(summary), " " * (col_w + 30 - 16 - len(str(len(summary))) - 20))
    log.info("+%s+", sep)

    counts: dict[ExtractionStatus, int] = {}
    for source_id, status in summary.items():
        meta = _STATUS_META.get(status, (status.value, "info", ""))
        label, level, _ = meta
        counts[status] = counts.get(status, 0) + 1
        getattr(log, level)("|  %-*s  %s", col_w, source_id, label)

    log.info("+%s+", sep)
    log.info("|  Counts:", )
    for status, count in sorted(counts.items(), key=lambda kv: kv[0].value):
        label = _STATUS_META.get(status, (status.value, "info", ""))[0]
        log.info("|    %s: %d", label, count)
    log.info("+%s+", sep)
    log.info("")


async def run(args: argparse.Namespace) -> int:
    """
    Orchestrate the full regulatory watch cycle.
    Returns 0 on success, 1 on fatal error.
    """
    # -- Dependency checks ----------------------------------------------------
    missing: list[str] = []
    if not _BS4_AVAILABLE:
        missing.append("beautifulsoup4")
    if not _HTTPX_AVAILABLE:
        missing.append("httpx")
    if not _PLAYWRIGHT_AVAILABLE:
        missing.append("playwright  (+ run: playwright install chromium)")
    if not _GENAI_AVAILABLE:
        missing.append("google-genai")
    if missing:
        log.error(
            "Missing required dependencies:\n  pip install %s",
            " ".join(m for m in missing if "playwright install" not in m),
        )
        return 1

    # -- Load sources ---------------------------------------------------------
    sources_path = Path(args.sources)
    if not sources_path.exists():
        log.error("Sources file not found: %s", sources_path)
        return 1

    all_sources: list[dict[str, Any]] = json.loads(
        sources_path.read_text(encoding="utf-8")
    ).get("sources", [])
    enabled = [s for s in all_sources if s.get("enabled", True)]
    js_needed = any(s.get("requires_js", False) for s in enabled)

    log.info(
        "Loaded %d source(s) -- %d enabled (%d require JS rendering).",
        len(all_sources),
        len(enabled),
        sum(1 for s in enabled if s.get("requires_js", False)),
    )

    if not enabled:
        log.warning("No enabled sources found -- nothing to do.")
        return 0

    # -- Load persisted state -------------------------------------------------
    state: dict[str, Any] = load_state()

    # -- Pre-flight gate check (Part C) ---------------------------------------
    global _preflight_checked
    if not _STATE_FILE.exists() or not state:
        estimated_calls = len(enabled)
        if not check_preflight_gate(estimated_calls, "regulatory_watch"):
            log.info("[QUOTA_GUARD] Pre-flight gate aborted by reviewer -- 0 API calls made.")
            return 0
        _preflight_checked = True

    # -- Per-source status accumulator (for the end-of-run summary) -----------
    # Maps source_id -> ExtractionStatus  (one entry per enabled source).
    run_summary: dict[str, ExtractionStatus] = {}

    # -- Run with Playwright context ------------------------------------------
    async with async_playwright() as pw:
        browser: Optional[Browser] = None
        playwright_page: Optional[Page] = None

        if js_needed:
            browser = await pw.chromium.launch(headless=not args.headed)
            context: BrowserContext = await browser.new_context(
                user_agent=_UA,
                viewport={"width": 1280, "height": 900},
                # Ignore HTTPS errors on government sites with odd cert chains
                ignore_https_errors=True,
            )
            playwright_page = await context.new_page()
            log.info("Playwright browser launched (headless=%s).", not args.headed)

        try:
            for idx, source in enumerate(enabled):
                source_id = source.get("id", "<unknown>")
                if _daily_quota_exhausted:
                    rem_sources = enabled[idx:]
                    log.warning(
                        "Daily Gemini quota exhausted -- skipping %d remaining source(s)/item(s) without further attempts.",
                        len(rem_sources),
                    )
                    for rem in rem_sources:
                        run_summary[rem.get("id", "<unknown>")] = ExtractionStatus.SKIPPED_QUOTA_EXHAUSTED
                    break

                try:
                    status = await _watch_source(
                        source=source,
                        state=state,
                        playwright_page=playwright_page,
                        dry_run=args.dry_run,
                    )
                    run_summary[source_id] = status
                    if _daily_quota_exhausted:
                        rem_sources = enabled[idx + 1:]
                        if rem_sources:
                            log.warning(
                                "Daily Gemini quota exhausted -- skipping %d remaining source(s)/item(s) without further attempts.",
                                len(rem_sources),
                            )
                            for rem in rem_sources:
                                run_summary[rem.get("id", "<unknown>")] = ExtractionStatus.SKIPPED_QUOTA_EXHAUSTED
                        break
                except Exception as exc:  # noqa: BLE001
                    # An unexpected exception that escaped _watch_source's own
                    # error handling -- record it so it appears in the summary.
                    log.error(
                        "  [SKIPPED_API_ERROR] Source '%s' raised an unexpected exception: "
                        "%s: %s",
                        source_id,
                        type(exc).__name__,
                        exc,
                        exc_info=args.verbose,  # full traceback only with --verbose
                    )
                    run_summary[source_id] = ExtractionStatus.SKIPPED_API_ERROR
                delay = source.get("delay_seconds", 4)
                log.debug("Polite delay: %ss", delay)
                await asyncio.sleep(delay)
        finally:
            if browser is not None:
                await browser.close()

    # -- Persist updated state ------------------------------------------------
    if args.dry_run:
        log.info("[DRY RUN] State NOT saved (pass without --dry-run to persist).")
    else:
        save_state(state)

    # -- End-of-run summary ---------------------------------------------------
    # Print one line per source so skipped / broken sources are never silently
    # indistinguishable from sources that were checked and found clean.
    _print_run_summary(run_summary)

    # Signal a non-zero exit if any source hit a hard error.
    error_statuses = {ExtractionStatus.SKIPPED_API_ERROR, ExtractionStatus.FETCH_ERROR}
    had_errors = any(s in error_statuses for s in run_summary.values())
    return 1 if had_errors else 0




