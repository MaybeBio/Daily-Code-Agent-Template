class ExtractionStatus(str, enum.Enum):
    """
    Unambiguous outcome codes returned by _extract_items_via_llm.

    SKIPPED_API_ERROR  - the Gemini API failed after all retries were exhausted.
    SKIPPED_PARSE_ERROR - the API responded but the output could not be parsed as JSON.
    NO_NEW_ITEMS        - the API responded and was parsed; genuinely no new items found.
    ITEMS_FOUND         - one or more new/changed items were successfully extracted.
    NO_CHANGE           - page hash matched; LLM was never called (set by _watch_source).
    FETCH_ERROR         - page could not be fetched; LLM was never called.
    """

    SKIPPED_API_ERROR   = "SKIPPED_API_ERROR"
    SKIPPED_QUOTA_EXHAUSTED = "SKIPPED_QUOTA_EXHAUSTED"
    SKIPPED_PARSE_ERROR = "SKIPPED_PARSE_ERROR"
    NO_NEW_ITEMS        = "NO_NEW_ITEMS"
    ITEMS_FOUND         = "ITEMS_FOUND"
    NO_CHANGE           = "NO_CHANGE"
    FETCH_ERROR         = "FETCH_ERROR"
    CACHE_HIT           = "CACHE_HIT"


