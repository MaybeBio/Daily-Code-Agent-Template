def _get_llm_client() -> Any:
    """Return a cached google.genai Client, initialising it on first call."""
    global _llm_client
    if _llm_client is not None:
        return _llm_client
    if not _GENAI_AVAILABLE:
        raise RuntimeError(
            "google-genai is not installed.\n"
            "  pip install google-genai"
        )
    api_key = os.environ.get("GOOGLE_API_KEY", "").strip()
    if not api_key:
        raise RuntimeError(
            "GOOGLE_API_KEY environment variable is not set.\n"
            "  Copy .env.example -> .env and add your key."
        )
    _llm_client = genai.Client(api_key=api_key)
    log.debug("Gemini client initialised (model: %s).", _llm_model)
    return _llm_client


