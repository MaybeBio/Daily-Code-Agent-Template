def load_dry_run_cache() -> dict[str, Any]:
    """Load the dry-run LLM response cache from storage/dry_run_llm_cache.json."""
    if _DRY_RUN_CACHE_FILE.exists():
        try:
            return json.loads(_DRY_RUN_CACHE_FILE.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError) as exc:
            log.warning("Could not read dry_run_llm_cache.json: %s", exc)
    return {}


def save_dry_run_cache(cache: dict[str, Any]) -> None:
    """Persist the dry-run LLM response cache to storage/dry_run_llm_cache.json."""
    try:
        _DRY_RUN_CACHE_FILE.parent.mkdir(parents=True, exist_ok=True)
        _DRY_RUN_CACHE_FILE.write_text(
            json.dumps(cache, indent=2, ensure_ascii=False, sort_keys=True),
            encoding="utf-8",
        )
        log.debug("Dry-run cache saved -> %s", _DRY_RUN_CACHE_FILE)
    except OSError as exc:
        log.warning("Could not save dry-run cache to %s: %s", _DRY_RUN_CACHE_FILE, exc)


def get_cached_llm_response(content_hash: str) -> Optional[ExtractionResult]:
    """Return a cached ExtractionResult for content_hash if present, or None."""
    cache = load_dry_run_cache()
    entry = cache.get(content_hash)
    if not entry:
        return None

    if isinstance(entry, list):
        status = ExtractionStatus.ITEMS_FOUND if entry else ExtractionStatus.NO_NEW_ITEMS
        detail = f"{len(entry)} item(s) from cache."
        return ExtractionResult(status=status, items=entry, detail=detail)

    if isinstance(entry, dict):
        status_val = entry.get("status")
        try:
            status = ExtractionStatus(status_val) if status_val else None
        except (ValueError, TypeError):
            status = None

        items = entry.get("items", [])
        if status is None:
            status = ExtractionStatus.ITEMS_FOUND if items else ExtractionStatus.NO_NEW_ITEMS
        detail = entry.get("detail", f"{len(items)} item(s) from cache.")
        return ExtractionResult(status=status, items=items, detail=detail)

    return None


def cache_llm_response(
    content_hash: str,
    source_id: str,
    result: ExtractionResult,
) -> None:
    """Store a successful real API call result in the dry-run cache."""
    # Only cache successful API extractions (ITEMS_FOUND or NO_NEW_ITEMS)
    if result.status not in (ExtractionStatus.ITEMS_FOUND, ExtractionStatus.NO_NEW_ITEMS):
        return
    cache = load_dry_run_cache()
    cache[content_hash] = {
        "source_id": source_id,
        "status": result.status.value,
        "items": result.items,
        "detail": result.detail,
        "cached_at": datetime.now(timezone.utc).isoformat(),
    }
    save_dry_run_cache(cache)


def sha256_of(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


