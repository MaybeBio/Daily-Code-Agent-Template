def _build_record(
    source: dict[str, Any],
    item: dict[str, Any],
    content_hash: str,
) -> dict[str, Any]:
    """Assemble a pending_items.jsonl record from a source config and an extracted item."""
    return {
        "id": str(uuid.uuid4()),
        "source_type": "regulatory",
        "title": (item.get("title") or "").strip() or "Untitled guidance",
        "agency": source.get("agency", "Unknown"),
        "url": item.get("url"),
        # True when the LLM explicitly could not find a URL on the page.
        "url_unknown": bool(item.get("url_unknown", False)),
        "publication_date": item.get("publication_date"),
        # True when the LLM explicitly could not find a publication date on the page.
        "date_unknown": bool(item.get("date_unknown", False)),
        # The description must be LLM-generated; never verbatim regulatory text.
        "description": (item.get("description") or "").strip(),
        "synthesis_method": item.get("synthesis_method", "gemini"),
        "detected_at": datetime.now(timezone.utc).isoformat(),
        "content_hash": content_hash,
        "source_id": source.get("id", ""),
        "index_url": source.get("url", ""),
        "model_name": _llm_model if item.get("synthesis_method", "gemini") == "gemini" else None,
        "config_versions": {"taxonomy_version": "1.1", "queries_version": "1.1"},
    }


def _append_record(record: dict[str, Any], dry_run: bool) -> None:
    """Append one JSONL record to pending_items.jsonl (or log it in dry-run mode)."""
    line = json.dumps(record, ensure_ascii=False)
    if dry_run:
        log.info("[DRY RUN] Would append -> %s", line)
        return
    _OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with _OUTPUT_FILE.open("a", encoding="utf-8") as fh:
        fh.write(line + "\n")
    log.info("  [OK] Appended: %s", record["title"])


